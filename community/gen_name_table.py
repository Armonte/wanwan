"""Convert PovertyCaster's pc-core NameTable.inc (the client's name rule table, COMMUNITY_TICKET_SPEC.md section 10)
into community/name_table.py, so the service refuses exactly what clients refuse.

    python3 community/gen_name_table.py <pc-core>/src/community/NameTable.inc > community/name_table.py
"""
import re
import sys


def main(path: str) -> None:
    text = open(path, encoding="utf-8").read()
    first = text.splitlines()[0]
    out = ["# GENERATED by community/gen_name_table.py from pc-core NameTable.inc -- do not edit.",
           "# source: " + first.lstrip("/ ").strip(), ""]
    for name in ("kNameBad", "kNameMark"):
        m = re.search(name + r"\[\] = \{(.*?)\};", text, re.S)
        if not m:
            sys.exit(f"{name} not found in {path}")
        pairs = re.findall(r"\{0x([0-9A-Fa-f]+), 0x([0-9A-Fa-f]+)\}", m.group(1))
        py = "NAME_BAD" if name == "kNameBad" else "NAME_MARK"
        out.append(f"{py} = (")
        row = []
        for lo, hi in pairs:
            row.append(f"(0x{lo}, 0x{hi})")
            if len(row) == 4:
                out.append("    " + ", ".join(row) + ",")
                row = []
        if row:
            out.append("    " + ", ".join(row) + ",")
        out.append(")")
        out.append("")
    sys.stdout.write("\n".join(out))


if __name__ == "__main__":
    main(sys.argv[1])
