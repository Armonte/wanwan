#!/usr/bin/env python3
"""Emit the public half of the release-signing key as a BCRYPT_RSAPUBLIC_BLOB.

CNG will not read a PEM. BCryptImportKeyPair wants the Windows blob layout:

    ULONG Magic       = 'RSA1' (0x31415352)
    ULONG BitLength
    ULONG cbPublicExp
    ULONG cbModulus
    ULONG cbPrime1    = 0   (public key: no primes)
    ULONG cbPrime2    = 0
    BYTE  PublicExponent[cbPublicExp]   big-endian
    BYTE  Modulus[cbModulus]            big-endian

Header fields are little-endian (it is a struct, not a wire format); the
two integers after them are big-endian. Getting that mix backwards is the
one way this goes wrong, so it is spelled out rather than inferred.
"""
import subprocess, sys, struct, re

BCRYPT_RSAPUBLIC_MAGIC = 0x31415352


def pubkey_parts(pem_path):
    out = subprocess.run(
        ["openssl", "rsa", "-in", pem_path, "-noout", "-modulus"],
        capture_output=True, text=True, check=True).stdout
    modulus_hex = out.strip().split("=", 1)[1]
    modulus = bytes.fromhex(modulus_hex)
    # openssl prints the exponent in the text dump; every key we generate
    # uses F4, but read it rather than assume it.
    txt = subprocess.run(
        ["openssl", "rsa", "-in", pem_path, "-noout", "-text"],
        capture_output=True, text=True, check=True).stdout
    m = re.search(r"Exponent:\s*(\d+)", txt)
    exp = int(m.group(1)) if m else 65537
    exp_bytes = exp.to_bytes((exp.bit_length() + 7) // 8, "big")
    return exp_bytes, modulus


def main():
    if len(sys.argv) != 3:
        sys.exit("usage: emit_release_key_header.py <private.pem> <out.h>")
    pem, out_h = sys.argv[1], sys.argv[2]
    exp, mod = pubkey_parts(pem)
    blob = struct.pack("<6I", BCRYPT_RSAPUBLIC_MAGIC, len(mod) * 8,
                       len(exp), len(mod), 0, 0) + exp + mod

    rows = []
    for i in range(0, len(blob), 12):
        rows.append("    " + " ".join(f"0x{b:02X}," for b in blob[i:i + 12]))

    with open(out_h, "w") as f:
        f.write(f"""// FM2K_ReleaseKey.h -- GENERATED by scripts/emit_release_key_header.py.
// Do not edit by hand; re-run scripts/make_signing_key.sh to rotate.
//
// The PUBLIC half of the release-signing key, already in the shape
// BCryptImportKeyPair wants (BCRYPT_RSAPUBLIC_BLOB). Committing a public
// key is the point: it is what lets a build refuse an update that was not
// signed by whoever holds the matching private key.
#pragma once
#include <cstddef>
#include <cstdint>

// RSA-{len(mod) * 8}, PKCS#1 v1.5 over SHA-256.
inline constexpr uint8_t kReleasePublicKeyBlob[] = {{
{chr(10).join(rows)}
}};
inline constexpr size_t kReleasePublicKeyBlobLen = sizeof(kReleasePublicKeyBlob);
""")
    print(f"{out_h}: RSA-{len(mod) * 8}, blob {len(blob)} bytes")


if __name__ == "__main__":
    main()
