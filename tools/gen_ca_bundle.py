#!/usr/bin/env python3
"""Regenerate launcher/net/tls/ca_bundle_mozilla.inc from curl's Mozilla CA extract.

The launcher's TLS client (launcher/net/tls/ca_store.cpp) trusts the Windows
ROOT store first and falls back to this bundled set when the store yields
nothing usable or lacks the issuing root (Windows 7 fetches roots on demand
through CryptoAPI chain building, which a non-CryptoAPI TLS stack never
triggers, so a stock Win7 store is often missing e.g. ISRG Root X1).

Usage:
    curl -sSLfo cacert.pem https://curl.se/ca/cacert.pem
    curl -sSLf https://curl.se/ca/cacert.pem.sha256   # compare by hand
    python3 -I tools/gen_ca_bundle.py cacert.pem launcher/net/tls/ca_bundle_mozilla.inc

Refresh it whenever a release goes out more than ~6 months after the date
recorded in the generated header.
"""
import base64
import datetime
import hashlib
import re
import sys


def main() -> int:
    if len(sys.argv) != 3:
        print(__doc__)
        return 2
    src, dst = sys.argv[1], sys.argv[2]
    raw = open(src, "rb").read()
    text = raw.decode("utf-8")
    m = re.search(r"Certificate data from Mozilla as of: (.+)", text)
    mozilla_date = m.group(1).strip() if m else "unknown"
    sha = hashlib.sha256(raw).hexdigest()

    certs = []
    label = None
    lines = text.splitlines()
    i = 0
    while i < len(lines):
        line = lines[i]
        if line and not line.startswith("#") and not line.startswith("=") and \
                i + 1 < len(lines) and lines[i + 1].startswith("==="):
            label = line.strip()
        if line.startswith("-----BEGIN CERTIFICATE-----"):
            b64 = []
            i += 1
            while not lines[i].startswith("-----END CERTIFICATE-----"):
                b64.append(lines[i].strip())
                i += 1
            certs.append((label or "?", base64.b64decode("".join(b64))))
            label = None
        i += 1

    out = []
    out.append("// GENERATED by tools/gen_ca_bundle.py -- do not edit by hand.")
    out.append("// Source: https://curl.se/ca/cacert.pem (Mozilla NSS certdata.txt extract,")
    out.append("//         trust bits for TLS server authentication only)")
    out.append(f"// Mozilla data as of: {mozilla_date}")
    out.append(f"// Generated: {datetime.date.today().isoformat()}  sha256(cacert.pem)={sha}")
    out.append(f"// Certificates: {len(certs)}  (DER, {sum(len(d) for _, d in certs)} bytes)")
    out.append("// License: the certificate data is MPL-2.0 (Mozilla); see THIRD-PARTY-NOTICES.md.")
    out.append("")
    for n, (lab, der) in enumerate(certs):
        safe = lab.replace("*/", "* /")
        out.append(f"/* {safe} */")
        out.append(f"static const unsigned char kMozillaRoot{n}[] = {{" +
                   ",".join(str(b) for b in der) + "};")
    out.append("")
    out.append("static const struct { const unsigned char* der; unsigned len; } kMozillaRoots[] = {")
    for n in range(len(certs)):
        out.append(f"    {{kMozillaRoot{n}, (unsigned)sizeof(kMozillaRoot{n})}},")
    out.append("};")
    out.append(f'static const char kMozillaRootsDate[] = "{mozilla_date}";')
    open(dst, "w", newline="\n").write("\n".join(out) + "\n")
    print(f"wrote {dst}: {len(certs)} certificates, Mozilla data as of {mozilla_date}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
